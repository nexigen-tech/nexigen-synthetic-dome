//! C++23 POD emission for contract schemas.

use crate::canonical::{self, FieldLayout, Layout};
use crate::diag::Diagnostics;
use crate::model::{
    ArrayCount, ContractSchema, EnumDef, PrimitiveType, RecordDef, Type, TypeDef, Version,
};
use std::collections::HashMap;
use std::fmt::Write;

/// Emits a C++23 header for a concrete contract schema.
pub fn emit(schema: &ContractSchema) -> Result<String, Diagnostics> {
    let mut out = String::new();
    let guard = format!("NXD_GENERATED_{}_HPP", schema.name.to_ascii_uppercase());

    writeln!(out, "// Generated by nxdc - do not edit manually.").unwrap();
    writeln!(out, "#ifndef {guard}").unwrap();
    writeln!(out, "#define {guard}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <array>").unwrap();
    writeln!(out, "#include <cstddef>").unwrap();
    writeln!(out, "#include <cstdint>").unwrap();
    writeln!(out, "#include <type_traits>").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace nxd::contracts {{")
        .unwrap();

    let registry = build_registry(schema);
    let mut emitted = HashMap::new();

    // Emit user-defined types in declaration order.
    for td in &schema.types {
        emit_type_def(&mut out, td, schema, &registry, &mut emitted)?;
    }

    // Emit top-level aggregate, sharing the emission set so dependencies are
    // not duplicated.
    emit_aggregate(&mut out, schema, &registry, &mut emitted)?;

    writeln!(out, "}} // namespace nxd::contracts").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#endif // {guard}").unwrap();

    Ok(out)
}

fn build_registry(schema: &ContractSchema) -> HashMap<String, TypeDef> {
    let mut map = HashMap::new();
    for td in &schema.types {
        map.insert(td.name().to_owned(), td.clone());
    }
    map
}

fn emit_type_def(
    out: &mut String,
    td: &TypeDef,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    if emitted.contains_key(td.name()) {
        return Ok(());
    }
    match td {
        TypeDef::Enum(en) => emit_enum(out, en, emitted),
        TypeDef::Record(rec) => emit_record(out, rec, schema, registry, emitted),
    }
}

fn emit_enum(
    out: &mut String,
    en: &EnumDef,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    let underlying = cpp_primitive(en.underlying);
    let layout = canonical::primitive_layout(en.underlying);
    writeln!(out, "enum class {} : {} {{", en.name, underlying).unwrap();
    for ev in &en.values {
        writeln!(out, "    {} = {},", ev.name, ev.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
    emitted.insert(en.name.clone(), layout);
    Ok(())
}

fn emit_record(
    out: &mut String,
    rec: &RecordDef,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    // Emit dependent types first.
    for field in &rec.fields {
        emit_dependencies(out, &field.ty, schema, registry, emitted)?;
    }

    let (layout, field_layouts) = canonical::record_layout(&rec.fields, registry, &mut HashMap::new())
        .map_err(|e| {
            let mut d = Diagnostics::new();
            d.push(format!("types.{}", rec.name), e.to_string());
            d
        })?;

    writeln!(out, "struct {} {{", rec.name).unwrap();
    let mut previous_end = 0usize;
    let mut pad_idx = 0usize;
    for fl in &field_layouts {
        if fl.offset > previous_end {
            let pad = fl.offset - previous_end;
            writeln!(
                out,
                "    std::array<std::uint8_t, {pad}> _pad{pad_idx};"
            )
            .unwrap();
            pad_idx += 1;
        }
        let cpp_ty = cpp_type(&fl.ty, registry);
        writeln!(out, "    {cpp_ty} {};", fl.name).unwrap();
        previous_end = fl.offset + fl.size;
    }
    if previous_end < layout.size {
        let pad = layout.size - previous_end;
        writeln!(
            out,
            "    std::array<std::uint8_t, {pad}> _pad{pad_idx};"
        )
        .unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    emit_static_asserts(out, &rec.name, layout, &field_layouts)?;
    emitted.insert(rec.name.clone(), layout);
    Ok(())
}

fn emit_aggregate(
    out: &mut String,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    for field in &schema.fields {
        emit_dependencies(out, &field.ty, schema, registry, emitted)?;
    }

    let (layout, field_layouts) = canonical::root_layout(schema).map_err(|e| {
        let mut d = Diagnostics::new();
        d.push(schema.name.clone(), e.to_string());
        d
    })?;

    writeln!(out, "struct {} {{", schema.name).unwrap();
    let mut previous_end = 0usize;
    let mut pad_idx = 0usize;
    for fl in &field_layouts {
        if fl.offset > previous_end {
            let pad = fl.offset - previous_end;
            writeln!(
                out,
                "    std::array<std::uint8_t, {pad}> _pad{pad_idx};"
            )
            .unwrap();
            pad_idx += 1;
        }
        let cpp_ty = cpp_type(&fl.ty, registry);
        writeln!(out, "    {cpp_ty} {};", fl.name).unwrap();
        previous_end = fl.offset + fl.size;
    }
    if previous_end < layout.size {
        let pad = layout.size - previous_end;
        writeln!(
            out,
            "    std::array<std::uint8_t, {pad}> _pad{pad_idx};"
        )
        .unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    emit_static_asserts(out, &schema.name, layout, &field_layouts)?;

    // Transport type identity.
    writeln!(
        out,
        "constexpr std::uint64_t {0}_layout_hash_hi = 0; // populated by consumer",
        schema.name
    )
    .unwrap();
    writeln!(
        out,
        "constexpr std::uint64_t {0}_layout_hash_lo = 0; // populated by consumer",
        schema.name
    )
    .unwrap();

    Ok(())
}

fn emit_dependencies(
    out: &mut String,
    ty: &Type,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    match ty {
        Type::Named(name) => {
            if emitted.contains_key(name) {
                return Ok(());
            }
            if let Some(td) = registry.get(name) {
                emit_type_def(out, td, schema, registry, emitted)?;
            }
        }
        Type::Array(element, _) => {
            emit_dependencies(out, element, schema, registry, emitted)?;
        }
        Type::Primitive(_) => {}
    }
    Ok(())
}

fn emit_static_asserts(
    out: &mut String,
    name: &str,
    layout: Layout,
    fields: &[FieldLayout],
) -> Result<(), Diagnostics> {
    writeln!(
        out,
        "static_assert(sizeof({name}) == {size}, \"sizeof {name}\");",
        size = layout.size
    )
    .unwrap();
    writeln!(
        out,
        "static_assert(alignof({name}) == {align}, \"alignof {name}\");",
        align = layout.alignment
    )
    .unwrap();
    for fl in fields {
        writeln!(
            out,
            "static_assert(offsetof({name}, {field}) == {offset}, \"offsetof {name}.{field}\");",
            field = fl.name,
            offset = fl.offset
        )
        .unwrap();
    }
    writeln!(
        out,
        "static_assert(std::is_trivially_copyable_v<{name}>, \"trivially copyable {name}\");"
    )
    .unwrap();
    writeln!(out).unwrap();
    Ok(())
}

fn cpp_type(ty: &Type, registry: &HashMap<String, TypeDef>) -> String {
    match ty {
        Type::Primitive(p) => cpp_primitive(*p).to_owned(),
        Type::Named(name) => name.clone(),
        Type::Array(element, ArrayCount::Literal(n)) => {
            format!("std::array<{}, {n}>", cpp_type(element, registry))
        }
        Type::Array(_, ArrayCount::Param(_)) => {
            panic!("cpp_type called on unresolved parametric array")
        }
    }
}

fn cpp_primitive(p: PrimitiveType) -> &'static str {
    match p {
        PrimitiveType::I8 => "std::int8_t",
        PrimitiveType::I16 => "std::int16_t",
        PrimitiveType::I32 => "std::int32_t",
        PrimitiveType::I64 => "std::int64_t",
        PrimitiveType::U8 => "std::uint8_t",
        PrimitiveType::U16 => "std::uint16_t",
        PrimitiveType::U32 => "std::uint32_t",
        PrimitiveType::U64 => "std::uint64_t",
        PrimitiveType::F32 => "float",
        PrimitiveType::F64 => "double",
    }
}

/// Returns a version string suitable for C++ constexpr context.
pub fn cpp_version(v: Version) -> String {
    format!("{} /* {}.{}.{} */", v.major, v.major, v.minor, v.patch)
}
