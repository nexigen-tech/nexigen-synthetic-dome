//! Rust `#[repr(C)]` emission for contract schemas.

use crate::canonical::{self, FieldLayout, Layout};
use crate::diag::Diagnostics;
use crate::model::{ArrayCount, ContractSchema, EnumDef, PrimitiveType, RecordDef, Type, TypeDef};
use std::collections::HashMap;
use std::fmt::Write;

/// Emits a Rust source file for a concrete contract schema.
pub fn emit(schema: &ContractSchema) -> Result<String, Diagnostics> {
    let mut out = String::new();
    writeln!(out, "// Generated by nxdc - do not edit manually.").unwrap();
    writeln!(out, "#![no_std]").unwrap();
    writeln!(out, "#![allow(non_upper_case_globals)]").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use core::mem::{{size_of, align_of, offset_of}};").unwrap();
    writeln!(out).unwrap();

    emit_zero_copy_trait(&mut out);

    let registry = build_registry(schema);
    let mut emitted = HashMap::new();

    // Emit user-defined types.
    for td in &schema.types {
        emit_type_def(&mut out, td, schema, &registry, &mut emitted)?;
    }

    // Emit top-level aggregate, sharing the emission set so dependencies are
    // not duplicated.
    emit_aggregate(&mut out, schema, &registry, &mut emitted)?;

    // Emit a compile-time check that every generated type implements the
    // zero-copy boundary contract.
    emit_zero_copy_asserts(&mut out, schema)?;

    Ok(out)
}

fn emit_zero_copy_trait(out: &mut String) {
    writeln!(
        out,
        "/// Marker trait for values that can cross the component"
    )
    .unwrap();
    writeln!(
        out,
        "/// boundary as raw bytes without copies, serialization, or"
    )
    .unwrap();
    writeln!(out, "/// lifetime checks.").unwrap();
    writeln!(out, "///").unwrap();
    writeln!(out, "/// # Safety").unwrap();
    writeln!(out, "/// Implementing this trait asserts that the type is:").unwrap();
    writeln!(out, "/// - `Copy + Send + Sync + 'static`;").unwrap();
    writeln!(
        out,
        "/// - made only of primitives and arrays of primitives;"
    )
    .unwrap();
    writeln!(
        out,
        "/// - free of pointers, references, atomics, Rust enums, strings,"
    )
    .unwrap();
    writeln!(
        out,
        "///   or any value whose validity depends on runtime invariants."
    )
    .unwrap();
    writeln!(
        out,
        "pub unsafe trait ZeroCopySend: Copy + Send + Sync + 'static {{}}"
    )
    .unwrap();
    writeln!(out).unwrap();
}

fn build_registry(schema: &ContractSchema) -> HashMap<String, TypeDef> {
    let mut map = HashMap::new();
    for td in &schema.types {
        map.insert(td.name().to_owned(), td.clone());
    }
    map
}

fn emit_type_def(
    out: &mut String,
    td: &TypeDef,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    if emitted.contains_key(td.name()) {
        return Ok(());
    }
    match td {
        TypeDef::Enum(en) => emit_enum(out, en, emitted),
        TypeDef::Record(rec) => emit_record(out, rec, schema, registry, emitted),
    }
}

fn emit_enum(
    out: &mut String,
    en: &EnumDef,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    let underlying = rust_primitive(en.underlying);
    let layout = canonical::primitive_layout(en.underlying);
    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]").unwrap();
    writeln!(out, "#[repr(transparent)]").unwrap();
    writeln!(out, "pub struct {}({underlying});", en.name).unwrap();
    writeln!(out).unwrap();
    for ev in &en.values {
        writeln!(
            out,
            "pub const {enum_name}_{value_name}: {enum_name} = {enum_name}({value});",
            enum_name = en.name,
            value_name = ev.name,
            value = ev.value
        )
        .unwrap();
    }
    writeln!(out).unwrap();
    writeln!(out, "unsafe impl ZeroCopySend for {} {{}}", en.name).unwrap();
    writeln!(out).unwrap();
    emitted.insert(en.name.clone(), layout);
    Ok(())
}

fn emit_record(
    out: &mut String,
    rec: &RecordDef,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    for field in &rec.fields {
        emit_dependencies(out, &field.ty, schema, registry, emitted)?;
    }

    let (layout, field_layouts) =
        canonical::record_layout(&rec.fields, registry, &mut HashMap::new()).map_err(|e| {
            let mut d = Diagnostics::new();
            d.push(format!("types.{}", rec.name), e.to_string());
            d
        })?;

    // Float fields implement PartialEq but not Eq, so we derive only the
    // traits that are valid for every generated POD.
    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq)]").unwrap();
    writeln!(out, "#[repr(C)]").unwrap();
    writeln!(out, "pub struct {} {{", rec.name).unwrap();
    let mut previous_end = 0usize;
    let mut pad_idx = 0usize;
    for fl in &field_layouts {
        if fl.offset > previous_end {
            let pad = fl.offset - previous_end;
            writeln!(out, "    pub _pad{pad_idx}: [u8; {pad}],").unwrap();
            pad_idx += 1;
        }
        let rust_ty = rust_type(&fl.ty, registry);
        writeln!(out, "    pub {}: {rust_ty},", fl.name).unwrap();
        previous_end = fl.offset + fl.size;
    }
    if previous_end < layout.size {
        let pad = layout.size - previous_end;
        writeln!(out, "    pub _pad{pad_idx}: [u8; {pad}],").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_layout_asserts(out, &rec.name, layout, &field_layouts)?;
    writeln!(out, "unsafe impl ZeroCopySend for {} {{}}", rec.name).unwrap();
    writeln!(out).unwrap();
    emitted.insert(rec.name.clone(), layout);
    Ok(())
}

fn emit_aggregate(
    out: &mut String,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    for field in &schema.fields {
        emit_dependencies(out, &field.ty, schema, registry, emitted)?;
    }

    let (layout, field_layouts) = canonical::root_layout(schema).map_err(|e| {
        let mut d = Diagnostics::new();
        d.push(schema.name.clone(), e.to_string());
        d
    })?;

    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq)]").unwrap();
    writeln!(out, "#[repr(C)]").unwrap();
    writeln!(out, "pub struct {} {{", schema.name).unwrap();
    let mut previous_end = 0usize;
    let mut pad_idx = 0usize;
    for fl in &field_layouts {
        if fl.offset > previous_end {
            let pad = fl.offset - previous_end;
            writeln!(out, "    pub _pad{pad_idx}: [u8; {pad}],").unwrap();
            pad_idx += 1;
        }
        let rust_ty = rust_type(&fl.ty, registry);
        writeln!(out, "    pub {}: {rust_ty},", fl.name).unwrap();
        previous_end = fl.offset + fl.size;
    }
    if previous_end < layout.size {
        let pad = layout.size - previous_end;
        writeln!(out, "    pub _pad{pad_idx}: [u8; {pad}],").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_layout_asserts(out, &schema.name, layout, &field_layouts)?;

    writeln!(out, "unsafe impl ZeroCopySend for {} {{}}", schema.name).unwrap();
    writeln!(out).unwrap();

    // Transport type identity constants.
    writeln!(
        out,
        "pub const {}_LAYOUT_HASH_HI: u64 = 0; // populated by consumer",
        schema.name.to_ascii_uppercase()
    )
    .unwrap();
    writeln!(
        out,
        "pub const {}_LAYOUT_HASH_LO: u64 = 0; // populated by consumer",
        schema.name.to_ascii_uppercase()
    )
    .unwrap();

    Ok(())
}

fn emit_dependencies(
    out: &mut String,
    ty: &Type,
    schema: &ContractSchema,
    registry: &HashMap<String, TypeDef>,
    emitted: &mut HashMap<String, Layout>,
) -> Result<(), Diagnostics> {
    match ty {
        Type::Named(name) => {
            if emitted.contains_key(name) {
                return Ok(());
            }
            if let Some(td) = registry.get(name) {
                emit_type_def(out, td, schema, registry, emitted)?;
            }
        }
        Type::Array(element, _) => {
            emit_dependencies(out, element, schema, registry, emitted)?;
        }
        Type::Primitive(_) => {}
    }
    Ok(())
}

fn emit_layout_asserts(
    out: &mut String,
    name: &str,
    layout: Layout,
    fields: &[FieldLayout],
) -> Result<(), Diagnostics> {
    writeln!(
        out,
        "const _: () = assert!(size_of::<{name}>() == {size}, \"size_of {name}\");",
        size = layout.size
    )
    .unwrap();
    writeln!(
        out,
        "const _: () = assert!(align_of::<{name}>() == {align}, \"align_of {name}\");",
        align = layout.alignment
    )
    .unwrap();
    for fl in fields {
        writeln!(
            out,
            "const _: () = assert!(offset_of!({name}, {}) == {offset}, \"offset_of {name}.{}\");",
            fl.name,
            fl.name,
            offset = fl.offset
        )
        .unwrap();
    }
    writeln!(out).unwrap();
    Ok(())
}

fn emit_zero_copy_asserts(out: &mut String, schema: &ContractSchema) -> Result<(), Diagnostics> {
    writeln!(
        out,
        "// Compile-time check: every generated type is ZeroCopySend."
    )
    .unwrap();
    writeln!(out, "const _: () = {{").unwrap();
    writeln!(out, "    fn assert_zero_copy<T: ZeroCopySend>() {{}}").unwrap();
    for td in &schema.types {
        writeln!(out, "    let _ = assert_zero_copy::<{}>;", td.name()).unwrap();
    }
    writeln!(out, "    let _ = assert_zero_copy::<{}>;", schema.name).unwrap();
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
    Ok(())
}

#[allow(clippy::only_used_in_recursion)]
fn rust_type(ty: &Type, registry: &HashMap<String, TypeDef>) -> String {
    match ty {
        Type::Primitive(p) => rust_primitive(*p).to_owned(),
        Type::Named(name) => name.clone(),
        Type::Array(element, ArrayCount::Literal(n)) => {
            format!("[{}; {n}]", rust_type(element, registry))
        }
        Type::Array(_, ArrayCount::Param(_)) => {
            panic!("rust_type called on unresolved parametric array")
        }
    }
}

fn rust_primitive(p: PrimitiveType) -> &'static str {
    match p {
        PrimitiveType::I8 => "i8",
        PrimitiveType::I16 => "i16",
        PrimitiveType::I32 => "i32",
        PrimitiveType::I64 => "i64",
        PrimitiveType::U8 => "u8",
        PrimitiveType::U16 => "u16",
        PrimitiveType::U32 => "u32",
        PrimitiveType::U64 => "u64",
        PrimitiveType::F32 => "f32",
        PrimitiveType::F64 => "f64",
    }
}
